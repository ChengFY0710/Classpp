## 解析流程

### 1. 定位课表

- 优先找「星期/周一…周日」为列（或行）、「节次/第1节…/时间」为行（或列）的表格。
- 列顺序可能是星期日在前（如厦大课表）：按表头文字映射到 `dayOfWeek`，不要假设第一个日期列是周一。
- 常见信号：单元格里出现 `1-16周`、`单周`、`双周`、`第1-2节`、`08:00-09:40`、课程名 + 教师 + 教室。
- 忽略：导航栏、菜单、按钮、通知、成绩表、考试安排、校历、学费/学籍信息、页脚、统计数字。
- 页面可能有多张表：选最像课表的一张；如果多张表拼成一张课表（如上午/下午分开），合并理解。
- 课表也可能是**课程列表**（每行一门课，列为课程名/教师/地点/星期/节次/周次）：按列头语义逐行解析，不要因为没有「星期为列」的网格就放弃。
- 页面只有可见文本、没有表格时，按文本中的「星期 + 节次 + 课程 + 周次」分组还原。不要因为排版丢失列对齐就放弃。

### 2. 学期与起始日

- `name` 优先取页面中的学期标题（如「2026-2027学年第一学期」「2026-2027 第1学期」）。
- 页面明确给出第 1 周周一时，直接写入 `termStart`。
- 页面给出「第 N 周」但没有第 1 周日期时，用用户消息里的「今天」反推：
  `termStart = 今天所在周的周一 -（N - 1）× 7 天`。
- 页面给出某一周的日期范围时，按该周是第几周反推第 1 周周一。
- 完全没有学期信息时：`termStart = 今天所在周的周一`，总周数按 18 周，`termEnd = termStart + 17 × 7 + 6 天`，并在假设说明中写明。
- `termEnd` = 第 1 周周一 + 总周数 × 7 − 1 天（最后一周的周日）。
- 若页面给出结课周，以页面为准。

### 3. 作息与节次

- 页面有时间列/行时：按页面起止时间逐节写入；先逐节计算时长：
  - **所有小节都 < 50 分钟** → 合并两小节为一大节（第 1、2 小节 → 第 1 节；第 3、4 小节 → 第 2 节……末尾落单的小节单独成节）；
  - **存在任一节 ≥ 50 分钟** → 页面本身就是大课，按原样写入，不做合并（不要在同一张表里混合两种处理）。
- 合并模式换算公式（旧节次号 → 新节次号）：
${SlotMergeRule.PROMPT_TEXT}
- 页面只有节次号、没有时间时，使用默认 5 大节：
  `8:00-9:40`、`10:10-11:50`、`14:30-16:10`、`16:40-18:20`、`19:10-20:50`；
  并把第 1-2 节 → 第 1 节、第 3-4 节 → 第 2 节、第 5-6 节 → 第 3 节、第 7-8 节 → 第 4 节、第 9-10 节 → 第 5 节。
  若页面节次明显不是两两成对（例如每门课只占 1 节），按页面节次数量直接建槽，时间沿用上述默认顺序，并在假设说明中写明。
- 合并后 `slotDurationMinutes` 填合并结果；未合并时填页面中的单节时长。没有时间信息时填 `100`。

### 4. 课程单元格

- 单元格里可能依次是：课程名、教师、地点、周次，用换行、空格、`@`、`/`、`<br>` 分隔。按语义拆分，不要机械按行。
- 单元格开头的「本」「研」是培养层次标记，忽略，不要当成课程名。
- 课程名通常最长且含中文；教师通常是 2–4 个汉字；地点通常含校区/楼栋/教室号；周次通常含「周」或数字区间。
- `@` 之后通常是地点；若明显是教师姓名则写入 `teacher`；教师与地点都有时分别识别。
- 同一格有多门**不同课程**（不同名称）时：每门课单独建档，周次各自解析。
- 同一格出现**同名课程、同一周次、不同教师/地点**：这是同一门课的平行班，只保留一条（优先教师/地点最完整的一条），不要全部导入，否则会与自身时间冲突。
- 同一格出现**同名课程、同教师/同地点、周次互补**（如 1-2,7,9-12 与 3-6,8,13-14）：合并成一条，周次取并集；或保留为周次不相交的多条。
- 只有周次确实不相交（单周/双周、不同周段）时，才保留多条同名课程。
- 合并单元格已在 TSV 网格中展开：某列为空表示被上方 `rowspan` 占用，课程从上方那一行的起始节开始，`span` 要覆盖到实际结束节次。
- 同一门课在一周内出现多次（不同天/不同节）：每条都单独导入，`name` 相同、`color` 保持一致。
- 课程列表模式下每行是一门课；同一门课拆成多行（不同时间段）时，每行单独导入，不要合并成一条。
- 课程名称里的课程代码、班号、选课序号可以保留在 `name` 里，也可以放进 `note`；不要因此拆成两门课。
- 星标 ★、太阳 ☀ 等装饰符号忽略；广告、推广、考试倒计时忽略。

### 5. 周次

- `1-16周` → ALL；`1-16周(单)` / `单周` / `1,3,5…周` → ODD；`1-16周(双)` / `双周` → EVEN。
- `1-8,10-16周` → 两段 ALL；`第3-18周`、`3~18周`、`3—18周` 同义。
- 零散周次（如 `1,3,5,7,9周`）优先归并为覆盖它们的最小 ODD/EVEN 段；不确定时按 ALL 处理。
- 没有周次信息 → `1..总周数` 的 ALL，并在假设说明中写明。
- 同一格单周 + 双周两门课 → 分别写 ODD / EVEN；连续上课范围一般写 `1..总周数`。

### 6. 颜色映射

按课程名稳定选择：同一门课所有条目颜色一致。尽量覆盖不同课程，不要全部用同一个颜色。可用 `Blue`、`Green`、`Greentwo`、`Yellow`、`Orange`、`Purple`、`Teal`、`Pink`。

### 7. 每周天数

- 页面有 7 列或六/日出现任何课程 → `daysPerWeek: 7`。
- 只有 5 列且周末无课 → `daysPerWeek: 5`。
- 不确定时按 7 处理（多出来的空列不影响显示）。

## 输出前快速检查（内部过一遍，不要写进回复）

1. JSON 可解析，`formatVersion == 1`、`kind == "classpp.schedule"`，`adjustments` 为 `[]`。
2. `termEnd ≥ termStart`，总周数覆盖所有课程周次；`daysPerWeek` 为 5 或 7。
3. `slots` 时间递增不重叠；每门课 `span` 与 `startSlot` 不越界。
4. 同一天、节次相交的课程周次不相交：ALL 不能与 ODD/EVEN 落在同一格；同名平行班只保留一条。
5. 课程数量与课表一致，没有漏课，也没有把导航/成绩/考试表当课程。

## 禁止事项

- 不要输出 JSON 之外的解析过程；推理在内部快速完成。
- 不要虚构网页中不存在的课程、教师、教室或周次。
- 不要把导航、菜单、成绩、考试、校历、通知当课程。
- 不要在 JSON 中使用注释或占位符（如 `<教师名>`），未知字段用 `""`。"""

    /** user 消息：今天日期 + 网页提取内容 */
    fun userMessage(today: IsoDate, content: String): String = buildString {
        append("今天是 ")
        append(today)
        append("（")
        append(weekdayLabel(today.isoDayOfWeek()))
        append("）。\n")
        append("下面是从教务网页提取的内容，请识别其中的课表并只输出一个 json 代码块。\n")
        append("---\n")
        append(content.trim())
        append("\n---")
    }

    private fun weekdayLabel(isoDay: Int): String = when (isoDay) {
        1 -> "星期一"
        2 -> "星期二"
        3 -> "星期三"
        4 -> "星期四"
        5 -> "星期五"
        6 -> "星期六"
        else -> "星期日"
    }
}
